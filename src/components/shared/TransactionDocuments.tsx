import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Shield, FileText, Download, Receipt, ScrollText, Printer } from "lucide-react";

interface TransactionDoc {
  txId: string;
  vendorName: string;
  buyerName: string;
  item: string;
  amount: number;
  fee?: number;
  date: string;
  status: string;
  tracking?: string;
  industry?: string;
  taxBreakdown?: Record<string, any>;
  invoiceItems?: any[];
}

type DocType = "invoice" | "contract" | "tax";

const docMeta: Record<DocType, { label: string; icon: any; desc: string }> = {
  invoice: { label: "Invoice / Receipt", icon: FileText, desc: "Itemized order receipt" },
  contract: { label: "Pre-Order Contract", icon: ScrollText, desc: "Signed transaction contract" },
  tax: { label: "Tax Receipt", icon: Receipt, desc: "Tax & duty breakdown" },
};

const printDocument = (title: string, contentId: string) => {
  const content = document.getElementById(contentId);
  if (!content) return;
  const printWindow = window.open("", "_blank");
  if (!printWindow) return;
  printWindow.document.write(`
    <html><head><title>${title}</title>
    <style>
      body { font-family: system-ui, sans-serif; padding: 40px; max-width: 700px; margin: auto; color: #1a1a1a; }
      .header { display: flex; align-items: center; gap: 12px; margin-bottom: 24px; padding-bottom: 16px; border-bottom: 2px solid #166534; }
      .logo { width: 40px; height: 40px; border-radius: 8px; background: #166534; display: flex; align-items: center; justify-content: center; color: white; font-weight: bold; font-size: 14px; }
      h1 { font-size: 18px; margin: 0; } h2 { font-size: 14px; margin: 16px 0 8px; color: #555; text-transform: uppercase; letter-spacing: 1px; }
      .row { display: flex; justify-content: space-between; padding: 6px 0; font-size: 13px; border-bottom: 1px solid #eee; }
      .row-label { color: #666; } .row-value { font-weight: 600; }
      .total-row { border-top: 2px solid #166534; padding-top: 8px; margin-top: 8px; font-size: 15px; }
      .footer { margin-top: 32px; padding-top: 16px; border-top: 1px solid #ddd; font-size: 11px; color: #888; text-align: center; }
      .item-card { background: #f9fafb; border: 1px solid #e5e7eb; border-radius: 6px; padding: 10px; margin-bottom: 6px; font-size: 12px; display: flex; justify-content: space-between; }
      @media print { body { padding: 20px; } }
    </style></head><body>${content.innerHTML}
    <div class="footer">Generated by TrustLock OS · trustlockpay.lovable.app · ${new Date().toLocaleString()}</div>
    </body></html>
  `);
  printWindow.document.close();
  printWindow.print();
};

