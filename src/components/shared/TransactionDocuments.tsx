interface TransactionDocumentsProps {
  tx: TransactionDoc;
  compact?: boolean;
}

const TransactionDocuments = ({ tx, compact = false }: TransactionDocumentsProps) => {
  const [openDoc, setOpenDoc] = useState<DocType | null>(null);

  const handlePrint = (type: DocType) => {
    printDocument(docMeta[type].label, `doc-${type}`);
  };

  if (compact) {
    return (
      <>
        <div className="flex gap-1.5 flex-wrap">
          {(["invoice", "contract", "tax"] as DocType[]).map((type) => {
            const meta = docMeta[type];
            return (
              <Button key={type} variant="outline" size="sm" className="text-[10px] h-7 px-2 gap-1" onClick={() => setOpenDoc(type)}>
                <meta.icon className="w-3 h-3" /> {meta.label}
              </Button>
            );
          })}
        </div>
        <Dialog open={!!openDoc} onOpenChange={() => setOpenDoc(null)}>
          <DialogContent className="max-w-lg max-h-[80vh] overflow-y-auto">
            <DialogHeader>
              <DialogTitle className="flex items-center gap-2">
                <Shield className="w-4 h-4 text-primary" />
                {openDoc && docMeta[openDoc].label}
              </DialogTitle>
            </DialogHeader>
            <div className="space-y-4">
              {openDoc === "invoice" && <InvoiceView tx={tx} />}
              {openDoc === "contract" && <ContractView tx={tx} />}
              {openDoc === "tax" && <TaxView tx={tx} />}
              <Button className="w-full gap-2" onClick={() => openDoc && handlePrint(openDoc)}>
                <Printer className="w-4 h-4" /> Print / Save as PDF
              </Button>
            </div>
          </DialogContent>
        </Dialog>
      </>
    );
  }

  return (
    <div className="space-y-3">
      <h3 className="text-sm font-semibold flex items-center gap-2">
        <Download className="w-4 h-4 text-primary" /> Transaction Documents
        <Badge variant="secondary" className="text-[9px]">Free</Badge>
      </h3>
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-2">
        {(["invoice", "contract", "tax"] as DocType[]).map((type) => {
          const meta = docMeta[type];
          return (
            <Card key={type} className="cursor-pointer hover:border-primary/30 transition-colors" onClick={() => setOpenDoc(type)}>
              <CardContent className="p-3 flex items-center gap-3">
                <div className="w-9 h-9 rounded-lg bg-primary/10 flex items-center justify-center shrink-0">
                  <meta.icon className="w-4 h-4 text-primary" />
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-semibold truncate">{meta.label}</p>
                  <p className="text-[10px] text-muted-foreground">{meta.desc}</p>
                </div>
              </CardContent>
            </Card>
          );
        })}
      </div>

      <Dialog open={!!openDoc} onOpenChange={() => setOpenDoc(null)}>
        <DialogContent className="max-w-lg max-h-[80vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <Shield className="w-4 h-4 text-primary" />
              {openDoc && docMeta[openDoc].label}
            </DialogTitle>
          </DialogHeader>
          <div className="space-y-4">
            {openDoc === "invoice" && <InvoiceView tx={tx} />}
            {openDoc === "contract" && <ContractView tx={tx} />}
            {openDoc === "tax" && <TaxView tx={tx} />}
            <Button className="w-full gap-2" onClick={() => openDoc && handlePrint(openDoc)}>
              <Printer className="w-4 h-4" /> Print / Save as PDF
            </Button>
          </div>
        </DialogContent>
      </Dialog>
    </div>
  );
};

export default TransactionDocuments;
export type { TransactionDoc };
